/**
 * Числовые константы воркера, вынесенные из точки входа `src/index.ts`.
 *
 * Cloudflare Workers трактует каждый именованный export из entry-модуля как
 * отдельный entrypoint (Durable Object, Workflow и т.п.) и падает при старте
 * с `Incorrect type for map entry ...: not of type 'function or ExportedHandler'`,
 * если это не функция. Поэтому значения, которые нужны тестам, живут здесь,
 * а не в `index.ts`.
 */

/** Размер кадра по умолчанию для генерации AI-версии. */
export const DEFAULT_FRAME_SIZE = 1024;

/**
 * Таймаут vision-запроса держим заметно ниже ~18 с — предела, после которого
 * Cloudflare рвёт клиентское соединение, если воркер ещё молчит. Иначе 504
 * не успевает дойти до клиента, и тот видит оборванный `Recv failure`.
 */
export const CLASSIFY_TIMEOUT_MS = 15_000;

/**
 * Предел ожидания готовой картинки. Провайдер генерации асинхронный: задача
 * ставится в очередь, её статус опрашивается, и только потом скачивается файл.
 *
 * 95 с — по факту: 20.10.2026 IskraGen отдавал кадр за 62, 76 и 82 с, а старый
 * предел 75 с обрывал ожидание раньше — картинка оплачивалась, но до клиента
 * не доходила. Выше ~100 с нельзя: столько Cloudflare держит соединение.
 */
export const GENERATE_TIMEOUT_MS = 95_000;

/** Пауза между опросами статуса. 2.5 с × 38 = 95 с, с запасом под лимит подзапросов. */
export const GENERATE_POLL_INTERVAL_MS = 2_500;

/** Таймаут одного запроса статуса или скачивания результата. */
export const IMAGE_DOWNLOAD_TIMEOUT_MS = 30_000;

/** Каталог моделей и цен — вспомогательный запрос: долго ждать его незачем. */
export const MODELS_TIMEOUT_MS = 8_000;

/** Потолок входного изображения генерации в decoded-байтах (D13). Оригинал
 * приходит от клиента в base64; клиент сжимает его до ~2000 px / JPEG, так что
 * 8 МБ — заведомый запас, при этом заметно ниже лимита провайдера (30 МБ
 * на файл в `POST /v1/files/`).
 */
export const MAX_GENERATE_INPUT_BYTES = 8 * 1024 * 1024;

/**
 * Потолок JSON-тела `POST /generate`. Поднят для входной картинки (D13): base64
 * раздувает декодированные байты примерно на треть, плюс JSON-обвязка.
 * 12 МБ тела ≈ 8.8 МБ декодированных байтов — покрывает {@link MAX_GENERATE_INPUT_BYTES}.
 */
export const MAX_GENERATE_BODY_BYTES = 12 * 1024 * 1024;

/** Потолок размера результата: защита от гигантского файла от провайдера. */
export const MAX_GENERATE_IMAGE_BYTES = 15 * 1024 * 1024;

/** Квадратный кадр, который ждёт приложение (карточка, сетка, коллаж). */
export const GENERATE_ASPECT = "1:1";

/** Разрешение провайдера: 1K — базовая цена, 2K/4K дороже. */
export const GENERATE_RESOLUTION = "1K";
