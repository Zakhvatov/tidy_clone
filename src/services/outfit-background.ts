/**
 * Подложка образа (T16).
 *
 * В доменном типе `Образ` нет цвета подложки: он задан до T16 и не меняется.
 * Поэтому выбор подложки — это настройка отображения, и живёт она в
 * `localStorage` рядом с устройством, а не в IndexedDB. Композиция образа
 * (элементы, слои, название, сезон) по-прежнему хранится в `outfits`.
 *
 * Модуль не зависит от React и от IndexedDB — только браузерное хранилище.
 */

/** Подложка по умолчанию — белый из ADR-0005. */
export const ФОН_ПО_УМОЛЧАНИЮ = '#FFFFFF'

/** Варианты подложки: минимум три, включая белую и тёплый `#F6F6F4`. */
export const ФОНЫ: ReadonlyArray<{ значение: string; метка: string }> = [
  { значение: '#FFFFFF', метка: 'Белый' },
  { значение: '#F6F6F4', метка: 'Тёплый' },
  { значение: '#EDEDEA', метка: 'Серый' },
  { значение: '#EFE7DD', метка: 'Бежевый' },
  { значение: '#1B1B1B', метка: 'Тёмный' },
]

const ПРЕФИКС_КЛЮЧА = 'tidy.outfit.background.'

function ключ(idОбраза: string): string {
  return `${ПРЕФИКС_КЛЮЧА}${idОбраза}`
}

/** Читает сохранённую подложку образа; при отсутствии или ошибке — белая. */
export function загрузитьФон(idОбраза: string): string {
  try {
    return localStorage.getItem(ключ(idОбраза)) ?? ФОН_ПО_УМОЛЧАНИЮ
  } catch {
    return ФОН_ПО_УМОЛЧАНИЮ
  }
}

/** Сохраняет подложку образа. Ошибки хранилища не должны ломать редактор. */
export function сохранитьФон(idОбраза: string, значение: string): void {
  try {
    localStorage.setItem(ключ(idОбраза), значение)
  } catch {
    // Приватный режим браузера может запрещать запись — молча пропускаем.
  }
}

/**
 * Убирает подложку удалённого образа. Без этого ключи копятся в `localStorage`
 * навсегда: образ исчез, а настройка осталась (утечка из финального ревью).
 * Подложка не входит в резервную копию (см. `docs/evidence/T19.md`) — это
 * осознанно, но мусор после удаления образа недопустим.
 */
export function удалитьФон(idОбраза: string): void {
  try {
    localStorage.removeItem(ключ(idОбраза))
  } catch {
    // Хранилище недоступно — чистить нечего.
  }
}
