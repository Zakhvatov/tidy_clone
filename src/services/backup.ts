/** Имя файла с датой: `wardrobe-backup-2026-10-14.json`. */
export function имяФайлаКопии(now: Date = new Date()): string {
  const год = now.getFullYear()
  const месяц = String(now.getMonth() + 1).padStart(2, '0')
  const день = String(now.getDate()).padStart(2, '0')
  return `wardrobe-backup-${год}-${месяц}-${день}.json`
}

function поИд(a: { id: string }, b: { id: string }): number {
  return a.id.localeCompare(b.id)
}

async function изображениеВКопию(изображение: Изображение): Promise<ИзображениеВКопии> {
  return {
    id: изображение.id,
    idВещи: изображение.idВещи,
    роль: изображение.роль,
    размер: изображение.blob.size,
    base64: await blobВBase64(изображение.blob),
    ширина: изображение.ширина,
    высота: изображение.высота,
    mime: изображение.mime,
    датаСоздания: изображение.датаСоздания,
  }
}

/**
 * Собирает резервную копию всего гардероба: вещи, изображения (байтами) и
 * образы. Порядок внутри файла — по `id`, чтобы один и тот же гардероб давал
 * один и тот же файл.
 */
export async function buildBackup(now: Date = new Date()): Promise<РезервнаяКопия> {
  const db = await getDb()
  const tx = db.transaction(['items', 'images', 'outfits'], 'readonly')
  const [вещи, изображения, образы] = await Promise.all([
    tx.objectStore('items').getAll(),
    tx.objectStore('images').getAll(),
    tx.objectStore('outfits').getAll(),
  ])
  await tx.done

  const изображенияВКопии: ИзображениеВКопии[] = []
  for (const изображение of изображения) {
    изображенияВКопии.push(await изображениеВКопию(изображение))
  }

  return {
    format: BACKUP_FORMAT,
    formatVersion: BACKUP_FORMAT_VERSION,
    createdAt: now.toISOString(),
    вещи: [...вещи].sort(поИд),
    изображения: изображенияВКопии.sort(поИд),
    образы: [...образы].sort(поИд),
  }
}

/** Готовый к скачиванию экспорт: blob, имя файла и то, что внутри. */
export interface ФайлКопии {
  blob: Blob
  имяФайла: string
  счётчики: СчётчикиИмпорта
}

/** Собирает один файл резервной копии. Ничего не отправляет в сеть. */
export async function exportWardrobe(now: Date = new Date()): Promise<ФайлКопии> {
  const копия = await buildBackup(now)
  return {
    blob: new Blob([JSON.stringify(копия, null, 2)], { type: 'application/json' }),
    имяФайла: имяФайлаКопии(now),
    счётчики: {
      вещи: копия.вещи.length,
      изображения: копия.изображения.length,
      образы: копия.образы.length,
    },
  }
}

/**
 * Отдаёт файл браузеру на скачивание. `URL.revokeObjectURL` откладывается на
 * макрозадачу: немедленный отзыв в некоторых браузерах отменяет загрузку.
 */
export function скачатьФайл(имяФайла: string, blob: Blob): void {
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = имяФайла
  link.rel = 'noopener'
  document.body.appendChild(link)
  link.click()
  link.remove()
  setTimeout(() => URL.revokeObjectURL(url), 0)
}

