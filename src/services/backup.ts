const РОЛИ: ReadonlySet<string> = new Set(['оригинал', 'ai', 'вырез'])
const СЕЗОНЫ: ReadonlySet<string> = new Set(['зима', 'лето', 'демисезон'])
const ИСТОЧНИКИ: ReadonlySet<string> = new Set(['ссылка', 'фото'])

function битый(сообщение: string): never {
  throw new ОшибкаРезервнойКопии('corrupt', сообщение)
}

function объект(value: unknown, путь: string): Record<string, unknown> {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) {
    битый(`Поле «${путь}» отсутствует или имеет неверный тип`)
  }
  return value as Record<string, unknown>
}

function массив(value: unknown, путь: string): unknown[] {
  if (!Array.isArray(value)) битый(`Поле «${путь}» отсутствует или не является списком`)
  return value
}

function строка(value: unknown, путь: string): string {
  if (typeof value !== 'string') битый(`Поле «${путь}» отсутствует или не является текстом`)
  return value
}

function число(value: unknown, путь: string): number {
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    битый(`Поле «${путь}» отсутствует или не является числом`)
  }
  return value
}

function строки(value: unknown, путь: string): string[] {
  return массив(value, путь).map((item, index) => строка(item, `${путь}[${index}]`))
}

function проверитьВещь(raw: unknown, index: number): Вещь {
  const путь = `вещи[${index}]`
  const o = объект(raw, путь)

  const сезон = массив(o.сезон, `${путь}.сезон`)
  for (const значение of сезон) {
    if (typeof значение !== 'string' || !СЕЗОНЫ.has(значение)) {
      битый(`${путь}.сезон: неизвестное значение «${String(значение)}»`)
    }
  }

  const источник = строка(o.источник, `${путь}.источник`)
  if (!ИСТОЧНИКИ.has(источник)) битый(`${путь}.источник: неизвестное значение «${источник}»`)

  return {
    id: строка(o.id, `${путь}.id`),
    название: строка(o.название, `${путь}.название`),
    категория: строка(o.категория, `${путь}.категория`),
    подкатегория: строка(o.подкатегория, `${путь}.подкатегория`),
    цвета: строки(o.цвета, `${путь}.цвета`),
    состав: строки(o.состав, `${путь}.состав`),
    сезон: сезон as Season[],
    бренд: строка(o.бренд, `${путь}.бренд`),
    источник: источник as ItemSource,
    ...(o.wbNmId === undefined ? {} : { wbNmId: число(o.wbNmId, `${путь}.wbNmId`) }),
    датаСоздания: строка(o.датаСоздания, `${путь}.датаСоздания`),
    датаОбновления: строка(o.датаОбновления, `${путь}.датаОбновления`),
    idИзображений: строки(o.idИзображений, `${путь}.idИзображений`),
  }
}

function проверитьИзображение(raw: unknown, index: number): ИзображениеВКопии {
  const путь = `изображения[${index}]`
  const o = объект(raw, путь)

  const id = строка(o.id, `${путь}.id`)
  const роль = строка(o.роль, `${путь}.роль`)
  if (!РОЛИ.has(роль)) битый(`${путь}.роль: неизвестная роль «${роль}»`)

  const размер = число(o.размер, `${путь}.размер`)
  if (размер < 0) битый(`${путь}.размер: не может быть отрицательным`)

  const base64 = строка(o.base64, `${путь}.base64`)
  const байты = раскодироватьBase64(base64, id)
  if (байты.byteLength !== размер) {
    битый(
      `Изображение «${id}»: повреждён base64 (ожидалось ${размер} байт, получено ${байты.byteLength})`,
    )
  }

  return {
    id,
    idВещи: строка(o.idВещи, `${путь}.idВещи`),
    роль: роль as ImageRole,
    размер,
    base64,
    ширина: число(o.ширина, `${путь}.ширина`),
    высота: число(o.высота, `${путь}.высота`),
    mime: строка(o.mime, `${путь}.mime`),
    датаСоздания: строка(o.датаСоздания, `${путь}.датаСоздания`),
  }
}

function проверитьОбраз(raw: unknown, index: number): Образ {
  const путь = `образы[${index}]`
  const o = объект(raw, путь)

  const сезон = строка(o.сезон, `${путь}.сезон`)
  if (!СЕЗОНЫ.has(сезон)) битый(`${путь}.сезон: неизвестное значение «${сезон}»`)

  const элементы = массив(o.элементы, `${путь}.элементы`).map((item, j) => {
    const элемент = объект(item, `${путь}.элементы[${j}]`)
    const позиция = объект(элемент.позиция, `${путь}.элементы[${j}].позиция`)
    return {
      idВещи: строка(элемент.idВещи, `${путь}.элементы[${j}].idВещи`),
      позиция: {
        x: число(позиция.x, `${путь}.элементы[${j}].позиция.x`),
        y: число(позиция.y, `${путь}.элементы[${j}].позиция.y`),
      },
      масштаб: число(элемент.масштаб, `${путь}.элементы[${j}].масштаб`),
      zПорядок: число(элемент.zПорядок, `${путь}.элементы[${j}].zПорядок`),
    }
  })

  return {
    id: строка(o.id, `${путь}.id`),
    название: строка(o.название, `${путь}.название`),
    сезон: сезон as Season,
    элементы,
    ...(o.обложкаИзображениеId === undefined
      ? {}
      : { обложкаИзображениеId: строка(o.обложкаИзображениеId, `${путь}.обложкаИзображениеId`) }),
    датаСоздания: строка(o.датаСоздания, `${путь}.датаСоздания`),
  }
}

/**
 * Таблица миграций старых версий формата. Сейчас известна одна версия, поэтому
 * шаг единичный; когда файлы версии 2 появятся, старые будут приводиться здесь
 * к текущей структуре до проверки — импорт не сломается на старом файле.
 */
const МИГРАЦИИ: Record<number, (документ: Record<string, unknown>) => Record<string, unknown>> = {
  1: (документ) => документ,
}

/** Разбирает и полностью проверяет документ. Битый файл дальше не проходит. */
export function проверитьКопию(raw: unknown): РезервнаяКопия {
  const документ = объект(raw, 'корень файла')

  if (документ.format !== BACKUP_FORMAT) {
    throw new ОшибкаРезервнойКопии('not_backup', 'Это не файл резервной копии гардероба')
  }

  const версия = документ.formatVersion
  if (typeof версия !== 'number' || !Number.isInteger(версия) || версия < 1) {
    throw new ОшибкаРезервнойКопии(
      'version',
      'В файле не указана версия формата — возможно, он повреждён',
    )
  }
  if (версия > BACKUP_FORMAT_VERSION) {
    throw new ОшибкаРезервнойКопии(
      'version',
      `Файл создан более новой версией приложения (формат ${версия}). Обновите приложение и попробуйте снова`,
    )
  }

  const миграция = МИГРАЦИИ[версия]
  if (миграция === undefined) {
    throw new ОшибкаРезервнойКопии(
      'version',
      `Формат резервной копии версии ${версия} не поддерживается`,
    )
  }
  const приведённый = миграция(документ)
  if (приведённый !== документ) return проверитьКопию(приведённый)

  const вещи = массив(документ.вещи, 'вещи').map(проверитьВещь)
  const изображения = массив(документ.изображения, 'изображения').map(проверитьИзображение)
  const образы = массив(документ.образы, 'образы').map(проверитьОбраз)

  const idВещей = new Set<string>()
  for (const вещь of вещи) {
    if (idВещей.has(вещь.id)) битый(`В файле две вещи с одинаковым id «${вещь.id}»`)
    idВещей.add(вещь.id)
  }

  const изображенияПоИд = new Map<string, ИзображениеВКопии>()
  for (const изображение of изображения) {
    if (изображенияПоИд.has(изображение.id)) {
      битый(`В файле два изображения с одинаковым id «${изображение.id}»`)
    }
    изображенияПоИд.set(изображение.id, изображение)
    if (!idВещей.has(изображение.idВещи)) {
      битый(`Изображение «${изображение.id}» ссылается на отсутствующую вещь «${изображение.idВещи}»`)
    }
  }

  for (const вещь of вещи) {
    for (const idИзображения of вещь.idИзображений) {
      if (!изображенияПоИд.has(idИзображения)) {
        битый(`Вещь «${вещь.id}» ссылается на отсутствующее изображение «${idИзображения}»`)
      }
    }
  }

  const idОбразов = new Set<string>()
  for (const образ of образы) {
    if (idОбразов.has(образ.id)) битый(`В файле два образа с одинаковым id «${образ.id}»`)
    idОбразов.add(образ.id)
    for (const элемент of образ.элементы) {
      if (!idВещей.has(элемент.idВещи)) {
        битый(`Образ «${образ.id}» ссылается на отсутствующую вещь «${элемент.idВещи}»`)
      }
    }
    if (образ.обложкаИзображениеId !== undefined && !изображенияПоИд.has(образ.обложкаИзображениеId)) {
      битый(`Образ «${образ.id}» ссылается на отсутствующее изображение «${образ.обложкаИзображениеId}»`)
    }
  }

  return {
    format: BACKUP_FORMAT,
    formatVersion: версия,
    createdAt: typeof документ.createdAt === 'string' ? документ.createdAt : '',
    вещи,
    изображения,
    образы,
  }
}

/** Разбирает текст файла. Не JSON → понятная ошибка `not_json`. */
export function разобратьКопию(text: string): РезервнаяКопия {
  let raw: unknown
  try {
    raw = JSON.parse(text)
  } catch {
    throw new ОшибкаРезервнойКопии('not_json', 'Это не файл резервной копии: не удалось прочитать JSON')
  }
  return проверитьКопию(raw)
}

