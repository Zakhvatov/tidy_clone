/** Кодирует байты в base64 порциями: `String.fromCharCode` не любит большие массивы. */
export function закодироватьБайты(bytes: Uint8Array): string {
  const CHUNK = 0x8000
  let binary = ''
  for (let offset = 0; offset < bytes.length; offset += CHUNK) {
    binary += String.fromCharCode(...bytes.subarray(offset, offset + CHUNK))
  }
  return btoa(binary)
}

/** Декодирует base64. `место` попадает в текст ошибки, чтобы назвать битое изображение. */
export function раскодироватьBase64(value: string, место: string): Uint8Array {
  const clean = value.replace(/\s+/g, '')
  if (clean.length % 4 !== 0 || !/^[A-Za-z0-9+/]*={0,2}$/.test(clean)) {
    throw new ОшибкаРезервнойКопии(
      'corrupt',
      `Изображение «${место}»: повреждён base64 — файл резервной копии испорчен`,
    )
  }
  let binary: string
  try {
    binary = atob(clean)
  } catch {
    throw new ОшибкаРезервнойКопии(
      'corrupt',
      `Изображение «${место}»: повреждён base64 — файл резервной копии испорчен`,
    )
  }
  const bytes = new Uint8Array(binary.length)
  for (let index = 0; index < binary.length; index += 1) {
    bytes[index] = binary.charCodeAt(index)
  }
  return bytes
}

/**
 * Читает байты `Blob`'а. `FileReader` — запасной путь: `Blob.arrayBuffer`
 * есть во всех целевых браузерах, но отсутствует в jsdom, где идут тесты.
 */
async function blobБайты(blob: Blob): Promise<Uint8Array> {
  if (typeof blob.arrayBuffer === 'function') {
    return new Uint8Array(await blob.arrayBuffer())
  }
  return new Promise((resolve, reject) => {
    const reader = new FileReader()
    reader.onload = () => resolve(new Uint8Array(reader.result as ArrayBuffer))
    reader.onerror = () => reject(reader.error ?? new Error('Не удалось прочитать изображение'))
    reader.readAsArrayBuffer(blob)
  })
}

/** Читает `Blob` как текст с той же оговоркой про jsdom. */
async function blobТекст(blob: Blob): Promise<string> {
  if (typeof blob.text === 'function') return blob.text()
  return new Promise((resolve, reject) => {
    const reader = new FileReader()
    reader.onload = () => resolve(String(reader.result))
    reader.onerror = () => reject(reader.error ?? new Error('Не удалось прочитать файл'))
    reader.readAsText(blob)
  })
}

async function blobВBase64(blob: Blob): Promise<string> {
  return закодироватьБайты(await blobБайты(blob))
}

function base64ВBlob(base64: string, mime: string, место: string): Blob {
  const байты = раскодироватьBase64(base64, место)
  // Копия в новый `ArrayBuffer`: так `Blob` гарантированно получает обычный
  // буфер, а не потенциально разделяемый.
  const данные = new Uint8Array(байты.byteLength)
  данные.set(байты)
  return new Blob([данные.buffer], {
    type: mime === '' ? 'application/octet-stream' : mime,
  })
}

