/**
 * Резервная копия гардероба (T19): экспорт и импорт одним файлом.
 *
 * Облака нет (раздел «Решения» `docs/tickets.md`), поэтому весь личный гардероб
 * должен целиком уезжать в один файл и так же целиком возвращаться на новое
 * устройство. Формат — обычный JSON с версией: `formatVersion` позволяет
 * распознать файл, сделанный другой (в том числе более новой) версией
 * приложения, и сказать об этом понятным текстом, а не сломать хранилище.
 *
 * Изображения (Оригиналы, AI-версии, вырезы) лежат в файле строками base64 —
 * без внешних зависимостей и без ZIP. Для личного гардероба это осознанный
 * размен: файл примерно на треть больше суммы картинок, зато распаковывается
 * любым редактором и не тянет в проект библиотеку. Байты сверяются с полем
 * `размер`, поэтому битый base64 ловится до записи в IndexedDB.
 *
 * Импорт — идемпотентное **объединение без удаления**. Правила совпадения id:
 * - вещь: если в базе новее (`датаОбновления`), она остаётся, входящая
 *   пропускается; иначе вещь обновляется;
 * - оригинал: изображение с занятым id и теми же размерами не дублируется;
 *   при отличающихся байтах сохраняется копия с новым id, а ссылка в вещи
 *   переставляется на неё — ни один байт не теряется (ADR-0002);
 * - образ: при совпадении id остаётся тот, что уже в базе (у образа нет
 *   `датаОбновления`, поэтому сравнить «свежесть» нельзя).
 * Вся запись идёт одной транзакцией: ошибка на середине откатывает импорт
 * целиком, существующий гардероб остаётся прежним.
 */

import type { ImageRole, ItemSource, Изображение, Образ, Season, Вещь } from '../domain/types'
import { getDb } from '../storage/db'

/** Маркер формата: по нему отличаем наш файл от любого другого JSON. */
export const BACKUP_FORMAT = 'tidy-clone-wardrobe'

/** Текущая версия формата. Растёт, когда меняется структура файла. */
export const BACKUP_FORMAT_VERSION = 1

/** Изображение внутри файла: байты заменены на base64. */
export interface ИзображениеВКопии {
  id: string
  idВещи: string
  роль: ImageRole
  /** Размер исходных байтов — для проверки, что base64 не побился. */
  размер: number
  base64: string
  ширина: number
  высота: number
  mime: string
  датаСоздания: string
}

/** Документ резервной копии — то, что лежит в файле. */
export interface РезервнаяКопия {
  format: string
  formatVersion: number
  createdAt: string
  вещи: Вещь[]
  изображения: ИзображениеВКопии[]
  образы: Образ[]
}

/** Код ошибки резервной копии: им пользуется UI для понятных подсказок. */
export type КодОшибкиКопии = 'not_json' | 'not_backup' | 'version' | 'corrupt' | 'storage'

/** Понятная русская ошибка импорта/экспорта. */
export class ОшибкаРезервнойКопии extends Error {
  readonly code: КодОшибкиКопии

  constructor(code: КодОшибкиКопии, message: string, options: { cause?: unknown } = {}) {
    super(message, options.cause === undefined ? undefined : { cause: options.cause })
    this.name = 'ОшибкаРезервнойКопии'
    this.code = code
  }
}

/** Сколько сущностей каждого вида. */
export interface СчётчикиИмпорта {
  вещи: number
  изображения: number
  образы: number
}

/** Что произошло с каждой сущностью при импорте. */
export interface ИтогИмпорта {
  добавлено: СчётчикиИмпорта
  обновлено: СчётчикиИмпорта
  пропущено: СчётчикиИмпорта
}

/** Валидированный файл с уже разобранными изображениями, но ещё не записанный. */
export interface ПодготовленныйИмпорт {
  версия: number
  создано: string
  вещи: Вещь[]
  изображения: Изображение[]
  образы: Образ[]
  /** Сколько сущностей лежит в файле. */
  вФайле: СчётчикиИмпорта
  /** Что будет сделано при записи (прогноз по текущему состоянию базы). */
  план: ИтогИмпорта
}

