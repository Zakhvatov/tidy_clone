interface СнимокБазы {
  датыОбновленияВещей: Map<string, string>
  изображенияПоИд: Map<string, Blob>
  idОбразов: Set<string>
}

/** Сравнивает байты двух изображений: одинаковые пропускаем, разные — копируем. */
async function одинаковыеБайты(первый: Blob, второй: Blob): Promise<boolean> {
  if (первый.size !== второй.size) return false
  const [а, б] = await Promise.all([blobБайты(первый), blobБайты(второй)])
  if (а.length !== б.length) return false
  for (let index = 0; index < а.length; index += 1) {
    if (а[index] !== б[index]) return false
  }
  return true
}

async function прочитатьСнимок(): Promise<СнимокБазы> {
  const db = await getDb()
  const tx = db.transaction(['items', 'images', 'outfits'], 'readonly')
  const [вещи, изображения, idОбразов] = await Promise.all([
    tx.objectStore('items').getAll(),
    tx.objectStore('images').getAll(),
    tx.objectStore('outfits').getAllKeys(),
  ])
  await tx.done

  return {
    датыОбновленияВещей: new Map(вещи.map((вещь) => [вещь.id, вещь.датаОбновления])),
    изображенияПоИд: new Map(изображения.map((изображение) => [изображение.id, изображение.blob])),
    idОбразов: new Set(idОбразов),
  }
}

interface ЗаписьВещи {
  вещь: Вещь
  новая: boolean
}

interface ПланЗаписи {
  вещи: ЗаписьВещи[]
  изображения: Изображение[]
  образы: Образ[]
  итог: ИтогИмпорта
}

function пустыеСчётчики(): СчётчикиИмпорта {
  return { вещи: 0, изображения: 0, образы: 0 }
}

/**
 * Считает, что именно будет записано, и готовит объекты к записи (в том числе
 * переназначает id изображений-копий). Ничего не пишет — это чистая функция
 * над снимком базы.
 */
async function спланировать(
  вещи: readonly Вещь[],
  изображения: readonly Изображение[],
  образы: readonly Образ[],
  снимок: СнимокБазы,
): Promise<ПланЗаписи> {
  const итог: ИтогИмпорта = {
    добавлено: пустыеСчётчики(),
    обновлено: пустыеСчётчики(),
    пропущено: пустыеСчётчики(),
  }

  const действияВещей = new Map<string, 'добавить' | 'обновить' | 'пропустить'>()
  for (const вещь of вещи) {
    const существующая = снимок.датыОбновленияВещей.get(вещь.id)
    if (существующая === undefined) {
      действияВещей.set(вещь.id, 'добавить')
      итог.добавлено.вещи += 1
    } else if (вещь.датаОбновления > существующая) {
      действияВещей.set(вещь.id, 'обновить')
      итог.обновлено.вещи += 1
    } else {
      действияВещей.set(вещь.id, 'пропустить')
      итог.пропущено.вещи += 1
    }
  }

  const импортируемыеВещи = new Set(
    [...действияВещей].filter(([, действие]) => действие !== 'пропустить').map(([id]) => id),
  )

  /** Для каждого id из файла — готовая запись или `null`, если писать нечего. */
  const действияИзображений = new Map<string, Изображение | null>()
  for (const изображение of изображения) {
    if (!импортируемыеВещи.has(изображение.idВещи)) {
      действияИзображений.set(изображение.id, null)
      итог.пропущено.изображения += 1
      continue
    }
    const существующее = снимок.изображенияПоИд.get(изображение.id)
    if (существующее === undefined) {
      действияИзображений.set(изображение.id, изображение)
      итог.добавлено.изображения += 1
      continue
    }
    if (await одинаковыеБайты(существующее, изображение.blob)) {
      // То же самое изображение уже в базе — не дублируем.
      действияИзображений.set(изображение.id, null)
      итог.пропущено.изображения += 1
      continue
    }
    // id занят, а байты другие: оставляем чужой оригинал нетронутым (ADR-0002)
    // и кладём копию под новым id. Ссылка в вещи переставится ниже.
    const копия: Изображение = { ...изображение, id: сгенерироватьId() }
    действияИзображений.set(изображение.id, копия)
    итог.добавлено.изображения += 1
  }

  const записиВещей: ЗаписьВещи[] = []
  for (const вещь of вещи) {
    const действие = действияВещей.get(вещь.id)
    if (действие === undefined || действие === 'пропустить') continue
    const idИзображений = вещь.idИзображений.map(
      (id) => действияИзображений.get(id)?.id ?? id,
    )
    записиВещей.push({ вещь: { ...вещь, idИзображений }, новая: действие === 'добавить' })
  }

  const записиИзображений = [...действияИзображений.values()].filter(
    (значение): значение is Изображение => значение !== null,
  )

  const записиОбразов: Образ[] = []
  for (const образ of образы) {
    if (снимок.idОбразов.has(образ.id)) {
      итог.пропущено.образы += 1
    } else {
      записиОбразов.push(образ)
      итог.добавлено.образы += 1
    }
  }

  return { вещи: записиВещей, изображения: записиИзображений, образы: записиОбразов, итог }
}

/** Читает файл, проверяет формат и считает план. В базу ничего не пишет. */
export async function prepareImport(file: Blob): Promise<ПодготовленныйИмпорт> {
  let text: string
  try {
    text = await blobТекст(file)
  } catch (cause) {
    throw new ОшибкаРезервнойКопии('not_json', 'Не удалось прочитать файл', { cause })
  }

  const копия = разобратьКопию(text)
  const изображения: Изображение[] = копия.изображения.map((изображение) => ({
    id: изображение.id,
    idВещи: изображение.idВещи,
    роль: изображение.роль,
    blob: base64ВBlob(изображение.base64, изображение.mime, изображение.id),
    ширина: изображение.ширина,
    высота: изображение.высота,
    mime: изображение.mime,
    датаСоздания: изображение.датаСоздания,
  }))

  const снимок = await прочитатьСнимок()
  const план = await спланировать(копия.вещи, изображения, копия.образы, снимок)

  return {
    версия: копия.formatVersion,
    создано: копия.createdAt,
    вещи: копия.вещи,
    изображения,
    образы: копия.образы,
    вФайле: {
      вещи: копия.вещи.length,
      изображения: копия.изображения.length,
      образы: копия.образы.length,
    },
    план: план.итог,
  }
}

/**
 * Записывает подготовленный импорт одной транзакцией на три стора. Любая
 * ошибка откатывает транзакцию целиком: гардероб остаётся прежним.
 */
export async function applyImport(подготовленный: ПодготовленныйИмпорт): Promise<ИтогИмпорта> {
  const снимок = await прочитатьСнимок()
  const план = await спланировать(
    подготовленный.вещи,
    подготовленный.изображения,
    подготовленный.образы,
    снимок,
  )

  const db = await getDb()
  const tx = db.transaction(['items', 'images', 'outfits'], 'readwrite')
  try {
    const itemsStore = tx.objectStore('items')
    for (const { вещь, новая } of план.вещи) {
      if (новая) {
        await itemsStore.add(вещь)
      } else {
        await itemsStore.put(вещь)
      }
    }

    const imagesStore = tx.objectStore('images')
    for (const изображение of план.изображения) {
      // Только `add`: чужой оригинал под тем же id перезаписать нельзя (ADR-0002).
      await imagesStore.add(изображение)
    }

    const outfitsStore = tx.objectStore('outfits')
    for (const образ of план.образы) {
      await outfitsStore.add(образ)
    }

    await tx.done
  } catch (cause) {
    try {
      tx.abort()
    } catch {
      // Транзакция уже завершилась — откатывать нечего.
    }
    await tx.done.catch(() => undefined)
    if (cause instanceof ОшибкаРезервнойКопии) throw cause
    throw new ОшибкаРезервнойКопии(
      'storage',
      'Не удалось записать резервную копию в хранилище. Гардероб остался прежним',
      { cause },
    )
  }

  return план.итог
}

export interface ОпцииИмпорта {
  /** Только проверить файл и показать план, ничего не записывать. */
  dryRun?: boolean
}

/**
 * Импортирует гардероб из файла. С `dryRun: true` проверяет файл и возвращает
 * план, не трогая базу, — этот режим использует экран для подтверждения.
 */
export async function importWardrobe(
  file: Blob,
  options: ОпцииИмпорта = {},
): Promise<ИтогИмпорта> {
  const подготовленный = await prepareImport(file)
  if (options.dryRun === true) return подготовленный.план
  return applyImport(подготовленный)
}
