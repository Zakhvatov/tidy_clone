/**
 * Фильтры и поиск по гардеробу (T14). Чистая логика: ни React, ни сети, ни
 * обращений к IndexedDB — только доменные `Вещь` на входе и на выходе.
 *
 * Решение пользователя из `docs/tickets.md` (T14): фильтры только по категории,
 * подкатегории, цвету и сезону. **Бренда и цены в фильтрах нет** — это прямо
 * запрещено, поэтому ни `filterItems`, ни `searchItems` их не учитывают.
 * Поиск идёт по названию (регистронезависимо, `ё → е`, по подстроке).
 *
 * Условия одного фильтра комбинируются по «И»: чтобы вещь прошла, она должна
 * подойти под каждое заданное условие. Внутри одного условия «цвета»/«сезоны»
 * действует «ИЛИ»: достаточно любого из выбранных значений. Пустой фильтр
 * возвращает все вещи.
 */

import { FALLBACK_TOP, isKnownTop, subcategoriesOf } from '../domain/taxonomy'
import type { Season, Вещь } from '../domain/types'

/** Условия фильтра. Незаданное (пустая строка, пустой массив) условие не влияет. */
export interface WardrobeFilter {
  top?: string
  sub?: string
  /** Достаточно совпадения с любым из выбранных цветов. */
  цвета?: string[]
  /** Достаточно совпадения с любым из выбранных сезонов. */
  сезоны?: Season[]
}

/** Сезоны в порядке показа чипов. */
export const СЕЗОНЫ: readonly Season[] = ['зима', 'лето', 'демисезон']

/**
 * Палитра частых цветов для правки вещи. Цвета в вещах — свободные строки из
 * карточек WB, поэтому палитра только предлагает типовые значения: цвета,
 * которых в ней нет, всё равно показываются отдельными чипами при правке.
 */
export const ПАЛИТРА_ЦВЕТОВ: readonly string[] = [
  'белый',
  'чёрный',
  'серый',
  'бежевый',
  'коричневый',
  'красный',
  'розовый',
  'оранжевый',
  'жёлтый',
  'зелёный',
  'оливковый',
  'голубой',
  'синий',
  'фиолетовый',
  'бордовый',
  'золотой',
  'серебряный',
]

/** Верхняя категория так, как её видит сетка: неизвестное — в «Разное». */
function нормализоватьВерх(категория: string): string {
  return isKnownTop(категория) ? категория : FALLBACK_TOP
}

/** Нормализация для поиска: регистр и `ё → е`. */
function нормализоватьДляПоиска(value: string): string {
  return value.trim().toLowerCase().replace(/ё/g, 'е')
}

/**
 * Фильтрует вещи по категории, подкатегории, цветам и сезонам. Условия
 * комбинируются по «И»; пустое условие не ограничивает. Верхняя категория
 * сравнивается с учётом «Разное»: вещь с неизвестной категорией попадает туда.
 */
export function filterItems(вещи: readonly Вещь[], filter: WardrobeFilter): Вещь[] {
  const top = filter.top?.trim() ?? ''
  const sub = filter.sub?.trim() ?? ''
  const цвета = filter.цвета ?? []
  const сезоны = filter.сезоны ?? []

  return вещи.filter((вещь) => {
    if (top !== '' && нормализоватьВерх(вещь.категория) !== top) return false
    if (sub !== '' && вещь.подкатегория !== sub) return false
    if (цвета.length > 0 && !цвета.some((цвет) => вещь.цвета.includes(цвет))) return false
    if (сезоны.length > 0 && !сезоны.some((сезон) => вещь.сезон.includes(сезон))) return false
    return true
  })
}

/**
 * Ищет по названию: регистронезависимо, `ё → е`, по подстроке. Пустой запрос
 * возвращает все вещи. Состав и бренд не участвуют — бренд не важен как
 * отдельный критерий (решение T14), а поиск задан именно по названию.
 */
export function searchItems(вещи: readonly Вещь[], query: string): Вещь[] {
  const запрос = нормализоватьДляПоиска(query)
  if (запрос === '') return [...вещи]
  return вещи.filter((вещь) => нормализоватьДляПоиска(вещь.название).includes(запрос))
}

/** Единая точка входа экрана: сначала фильтр, затем поиск по названию. */
export function filterAndSearch(
  вещи: readonly Вещь[],
  filter: WardrobeFilter,
  query: string,
): Вещь[] {
  return searchItems(filterItems(вещи, filter), query)
}

/** Цвета, которые реально есть в гардеробе: без пустых значений, по алфавиту. */
export function availableColors(вещи: readonly Вещь[]): string[] {
  const множество = new Set<string>()
  for (const вещь of вещи) {
    for (const цвет of вещь.цвета) {
      const значение = цвет.trim()
      if (значение !== '') множество.add(значение)
    }
  }
  return [...множество].sort((a, b) => a.localeCompare(b, 'ru'))
}

/** Сезоны, которые реально есть в гардеробе, в порядке чипов. */
export function availableSeasons(вещи: readonly Вещь[]): Season[] {
  const есть = new Set<Season>()
  for (const вещь of вещи) {
    for (const сезон of вещь.сезон) есть.add(сезон)
  }
  return СЕЗОНЫ.filter((сезон) => есть.has(сезон))
}

/**
 * Подкатегории, которые реально есть у вещей выбранной верхней категории.
 * Известные идут в порядке таксономии ADR-0004, неизвестные — по алфавиту
 * следом: словарь расширяемый, поэтому «чужое» значение не теряется.
 */
export function availableSubcategories(вещи: readonly Вещь[], top: string): string[] {
  const категория = top.trim()
  if (категория === '') return []
  const норма = нормализоватьВерх(категория)

  const есть = new Set<string>()
  for (const вещь of вещи) {
    if (нормализоватьВерх(вещь.категория) !== норма) continue
    const под = вещь.подкатегория.trim()
    if (под !== '') есть.add(под)
  }

  const порядок = subcategoriesOf(норма)
  const известные = порядок.filter((под) => есть.has(под))
  const прочие = [...есть]
    .filter((под) => !порядок.includes(под))
    .sort((a, b) => a.localeCompare(b, 'ru'))
  return [...известные, ...прочие]
}

/** Задан ли хотя бы один фильтр. Нужен экрану, чтобы показать счётчик и «Сбросить». */
export function hasActiveFilter(filter: WardrobeFilter): boolean {
  return (
    (filter.top?.trim() ?? '') !== '' ||
    (filter.sub?.trim() ?? '') !== '' ||
    (filter.цвета?.length ?? 0) > 0 ||
    (filter.сезоны?.length ?? 0) > 0
  )
}
