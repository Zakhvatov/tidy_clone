import { beforeEach, describe, expect, it } from 'vitest'

import { ФОН_ПО_УМОЛЧАНИЮ, ФОНЫ, загрузитьФон, сохранитьФон, удалитьФон } from './outfit-background'

describe('Подложка образа (T16)', () => {
  beforeEach(() => {
    localStorage.clear()
  })

  it('без сохранённого значения отдаёт белую подложку', () => {
    expect(загрузитьФон('неизвестный-образ')).toBe(ФОН_ПО_УМОЛЧАНИЮ)
  })

  it('сохраняет и читает подложку конкретного образа', () => {
    сохранитьФон('образ-1', '#F6F6F4')

    expect(загрузитьФон('образ-1')).toBe('#F6F6F4')
    // Подложка другого образа не затрагивается.
    expect(загрузитьФон('образ-2')).toBe(ФОН_ПО_УМОЛЧАНИЮ)
  })

  it('удаляет подложку только удалённого образа', () => {
    сохранитьФон('образ-1', '#EDEDEA')
    сохранитьФон('образ-2', '#EFE7DD')

    удалитьФон('образ-1')

    expect(загрузитьФон('образ-1')).toBe(ФОН_ПО_УМОЛЧАНИЮ)
    expect(загрузитьФон('образ-2')).toBe('#EFE7DD')
  })

  it('предлагает минимум три варианта, включая белую и тёплую подложки', () => {
    const значения = ФОНЫ.map((вариант) => вариант.значение)

    expect(значения.length).toBeGreaterThanOrEqual(3)
    expect(значения).toContain('#FFFFFF')
    expect(значения).toContain('#F6F6F4')
  })
})
