/**
 * Доменные типы цифрового гардероба.
 *
 * Имена полей и значения — из `docs/architecture.md` («Домен: обязательные сущности»)
 * и `CONTEXT.md`: домен говорит по-русски, поэтому поля названы по-русски, а не
 * транслитерированы. Имена union-типов оставлены латиницей, как принято в коде.
 */

/** Роль изображения. «Оригинал» неизменяем, «ai» и «вырез» — производные. */
export type ImageRole = 'оригинал' | 'ai' | 'вырез'

/** Сезон вещи и образа. */
export type Season = 'зима' | 'лето' | 'демисезон'

/** Источник появления вещи: импорт по ссылке или загрузка фото. */
export type ItemSource = 'ссылка' | 'фото'

/** Вещь — единица гардероба. */
export interface Вещь {
  id: string
  название: string
  категория: string
  подкатегория: string
  цвета: string[]
  состав: string[]
  сезон: Season[]
  бренд: string
  источник: ItemSource
  /** `nmId` карточки Wildberries, если вещь добавлена по ссылке. */
  wbNmId?: number
  /** ISO-8601, UTC. */
  датаСоздания: string
  /** ISO-8601, UTC. */
  датаОбновления: string
  /** id изображений вещи. */
  idИзображений: string[]
}

/** Изображение вещи: оригинал, AI-версия или точный вырез пакшота. */
export interface Изображение {
  id: string
  idВещи: string
  роль: ImageRole
  /** Пиксели хранятся как `Blob`, а не base64. */
  blob: Blob
  ширина: number
  высота: number
  mime: string
  /** ISO-8601, UTC. */
  датаСоздания: string
}

/** Элемент образа: какая вещь, где и как лежит в коллаже. */
export interface ЭлементОбраза {
  idВещи: string
  /** Позиция центра вещи в системе координат коллажа. */
  позиция: { x: number; y: number }
  масштаб: number
  zПорядок: number
}

/** Образ — сохранённая композиция вещей. */
export interface Образ {
  id: string
  название: string
  сезон: Season
  элементы: ЭлементОбраза[]
  /** id изображения-обложки, если обложка выбрана. */
  обложкаИзображениеId?: string
  /** ISO-8601, UTC. */
  датаСоздания: string
}
