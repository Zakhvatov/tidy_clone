/**
 * Словарь «таксономия WB → наша таксономия» (T7, ADR-0004).
 *
 * Зачем: у карточки Wildberries уже есть размеченные продавцом `subj_root_name`
 * (надкатегория) и `subj_name` (предмет). Категория вещи берётся детерминированным
 * словарём, а не нейросетью: бесплатно, мгновенно, воспроизводимо и без искажений.
 *
 * Откуда взяты строки (сырые выгрузки — в `docs/evidence/raw/`):
 *   - `wb-subject-base.fashion.json` — срез `subject-base.json` WB: реальные пары
 *     «корень → предмет» с их числовыми id. Это тот же справочник, из которого WB
 *     заполняет `subj_root_name`/`subj_name` и `data.subject_root_id`/`subject_id`.
 *   - `wb-cards-sample.json` — реальные `card.json`, которыми сверена связка
 *     «название в справочнике ↔ значение в карточке» (например, `subject_id: 295`,
 *     `subj_name: «Броши»`, `subject_root_id: 200`, `subj_root_name: «Бижутерия»`).
 *   - `wb-menu.json` — дерево категорий витрины, для перекрёстной сверки названий.
 *
 * Строки WB, которые нельзя разложить в одну нашу категорию (комплекты, купальники,
 * пижамы, спортивные костюмы), описаны ниже явно: они ведут в «Разное» с
 * `needsReview: true`, чтобы UI предложил выбрать вручную. См. `docs/evidence/T7.md`.
 *
 * Модуль чистый: ни React, ни сети. Зависит только от `taxonomy.ts`.
 */

import {
  FALLBACK_SUB,
  FALLBACK_TOP,
  TAXONOMY,
  isKnownSub,
  type TopCategory,
} from './taxonomy'

/** Верхняя категория словаря: известная из ADR-0004 либо «Разное». */
export type WbTop = TopCategory | typeof FALLBACK_TOP

/** Как строка WB нашла соответствие: по паре, только по предмету или никак. */
export type WbMatchKind = 'root+subject' | 'subject' | 'none'

/** Результат классификации строки WB. */
export interface WbCategoryMapping {
  top: WbTop
  sub: string
  /** `true` — уверенного соответствия нет, нужно подтверждение пользователя. */
  needsReview: boolean
  matchedBy: WbMatchKind
}

/** Одна строка словаря: пара WB → наша пара. */
export interface WbDictionaryEntry {
  /** `subj_root_name` из card.json (например, «Одежда»). */
  root: string
  /** `subj_name` из card.json (например, «Футболки»). */
  subject: string
  top: WbTop
  sub: string
}

