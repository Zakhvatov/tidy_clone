/**
 * Приводит значение WB к сравнимому виду: регистр, `ё`→`е`, кавычки, пунктуация,
 * лишние пробелы. Работает и для `subj_root_name`, и для `subj_name`.
 */
export function normalizeWbName(value: string | null | undefined): string {
  return (value ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[«»"'`]/g, '')
    .replace(/[(),.]/g, ' ')
    // «18+» — не часть названия предмета, а пометка (Футболки 18+).
    .replace(/\b18\s*\+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

/**
 * Разговорные синонимы и опечатки WB → канонический `subj_name` словаря.
 * Множественное/единственное число разбирается автоматически (см. `nameVariants`),
 * здесь — только то, что морфологией не выводится.
 */
export const WB_SUBJECT_ALIASES: Readonly<Record<string, string>> = {
  кроссы: 'кроссовки',
  кросы: 'кроссовки',
  балахон: 'худи',
  толстовка: 'толстовки',
  свитшот: 'свитшоты',
  джинсовка: 'куртки',
  майка: 'топы',
  бодик: 'боди',
}

/**
 * Варианты написания одного названия: само слово плюс сгенерированное единственное
 * число. Морфология русских существительных неполна (`ботинки` → `ботинок` тут не
 * выводится), поэтому для частых случаев достаточно «-ки → -ка» и отсечения гласной.
 */
export function nameVariants(normalized: string): string[] {
  const variants = new Set<string>([normalized])
  if (normalized.endsWith('ки')) variants.add(`${normalized.slice(0, -2)}ка`)
  if (normalized.endsWith('ги')) variants.add(`${normalized.slice(0, -2)}га`)
  if (normalized.endsWith('хи')) variants.add(`${normalized.slice(0, -2)}ха`)
  if (normalized.endsWith('ы')) variants.add(normalized.slice(0, -1))
  if (normalized.endsWith('и')) variants.add(normalized.slice(0, -1))
  return [...variants]
}

// ---------------------------------------------------------------------------
// Индексы
// ---------------------------------------------------------------------------

interface IndexedEntry extends WbDictionaryEntry {
  normRoot: string
  normSubject: string
}

const ROOT_SUBJECT_INDEX = new Map<string, IndexedEntry>()
const SUBJECT_INDEX = new Map<string, IndexedEntry | 'ambiguous'>()

function key(root: string, subject: string): string {
  return `${root}\u0000${subject}`
}

for (const entry of WB_DICTIONARY) {
  const normRoot = normalizeWbName(entry.root)
  const normSubject = normalizeWbName(entry.subject)
  const indexed: IndexedEntry = { ...entry, normRoot, normSubject }

  for (const subjectVariant of nameVariants(normSubject)) {
    const rootSubjectKey = key(normRoot, subjectVariant)
    if (!ROOT_SUBJECT_INDEX.has(rootSubjectKey)) ROOT_SUBJECT_INDEX.set(rootSubjectKey, indexed)

    // Индекс только по предмету: он нужен, когда корень не пришёл или назван иначе.
    const existing = SUBJECT_INDEX.get(subjectVariant)
    if (existing === undefined) {
      SUBJECT_INDEX.set(subjectVariant, indexed)
    } else if (existing === 'ambiguous') {
      // уже помечен как неоднозначный
    } else if (existing.top !== entry.top || existing.sub !== entry.sub) {
      // один предмет WB в двух корнях ведёт в разные наши категории — не угадываем.
      SUBJECT_INDEX.set(subjectVariant, 'ambiguous')
    }
  }
}

// ---------------------------------------------------------------------------
// API
// ---------------------------------------------------------------------------

function resolve(subject: string, root: string | null | undefined): WbCategoryMapping {
  const normRoot = normalizeWbName(root)
  const rawSubject = normalizeWbName(subject)
  const alias = WB_SUBJECT_ALIASES[rawSubject]
  const normSubject = alias ? normalizeWbName(alias) : rawSubject

  if (!normSubject) {
    return { top: FALLBACK_TOP, sub: FALLBACK_SUB, needsReview: true, matchedBy: 'none' }
  }

  // 1. Точная пара «корень + предмет».
  for (const variant of nameVariants(normSubject)) {
    const found = normRoot ? ROOT_SUBJECT_INDEX.get(key(normRoot, variant)) : undefined
    if (found) return toMapping(found, 'root+subject')
  }

  // 2. Только предмет: если он однозначен во всех корнях.
  for (const variant of nameVariants(normSubject)) {
    const found = SUBJECT_INDEX.get(variant)
    if (found && found !== 'ambiguous') return toMapping(found, 'subject')
  }

  return { top: FALLBACK_TOP, sub: FALLBACK_SUB, needsReview: true, matchedBy: 'none' }
}

function toMapping(entry: IndexedEntry, matchedBy: WbMatchKind): WbCategoryMapping {
  return {
    top: entry.top,
    sub: entry.sub,
    needsReview: entry.top === FALLBACK_TOP,
    matchedBy,
  }
}

/**
 * Классифицирует строки карточки WB.
 *
 * `subjRootName` — `subj_root_name`, `subjName` — `subj_name`. Оба могут быть пустыми:
 * тогда работает индекс только по предмету, а при неоднозначности — «Разное».
 * Неизвестное значение не теряется, а возвращается как «Разное»/«Разное» +
 * `needsReview: true`, чтобы UI предложил выбрать вручную.
 */
export function mapWbCategory(
  subjRootName: string | null | undefined,
  subjName: string | null | undefined,
): WbCategoryMapping {
  return resolve(subjName ?? '', subjRootName)
}

/** Сколько строк WB покрыто словарём. */
export function dictionarySize(): number {
  return WB_DICTIONARY.length
}

/**
 * Список строк WB, которые словарь осознанно не берёт на себя: комплекты, купальники,
 * пижамы, спортивные костюмы. UI показывает их как «выберите категорию».
 */
export function unknownSubjects(): readonly string[] {
  return WB_DICTIONARY.filter((entry) => entry.top === FALLBACK_TOP).map((entry) => entry.subject)
}

/** Все покрытые пары «корень + предмет» — для отладки и UI-подсказок. */
export function knownPairs(): ReadonlyArray<{ root: string; subject: string; top: WbTop; sub: string }> {
  return WB_DICTIONARY.map(({ root, subject, top, sub }) => ({ root, subject, top, sub }))
}

/** Внутренний инвариант: каждая запись словаря обязана указывать на нашу пару. */
export function isDictionaryConsistent(): boolean {
  return WB_DICTIONARY.every((entry) => isKnownSub(entry.top, entry.sub))
}

