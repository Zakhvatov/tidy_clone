/** Строка, которую нельзя свести к одной категории: «Разное» + ручной выбор. */
type Row = readonly [subject: string, top: WbTop, sub: string]

function group(root: string, rows: readonly Row[]): WbDictionaryEntry[] {
  return rows.map(([subject, top, sub]) => ({ root, subject, top, sub }))
}

