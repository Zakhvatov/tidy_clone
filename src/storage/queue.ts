/**
 * Стор `queue`: персистентное состояние очереди оцифровки (T12).
 *
 * Зачем в IndexedDB, а не в памяти: у Tidy массовая оцифровка падала на 96% и
 * теряла вещи. Очередь должна переживать закрытие приложения, поэтому её
 * состояние — те же данные на устройстве, что и гардероб, и живёт в той же БД.
 *
 * Очередь — служебная сущность, а не домен (`CONTEXT.md`), поэтому её типы
 * лежат здесь, рядом со стором, и не попадают в `domain/types.ts`.
 *
 * Запись одна — `id: 'active'`: личное приложение, одна очередь на устройство.
 * Каждый шаг переписывает запись целиком (`put`), это дешевле и надёжнее, чем
 * согласовывать частичные обновления задач.
 */

import { getDb } from './db'

/** Как оцифровывается вещь: точным вырезом пакшота или генерацией AI-версии. */
export type СпособОцифровки = 'вырез' | 'ai'

/** Статус одной задачи очереди. */
export type СтатусЗадачи = 'ожидает' | 'в работе' | 'готово' | 'не удалось'

/** Статус всей очереди. */
export type СтатусОчереди = 'ожидает' | 'выполняется' | 'остановлена' | 'завершена'

/** Одна задача очереди — одна вещь. */
export interface ЗадачаОчереди {
  /** `id` задачи = `id` вещи: одна задача на вещь, повтор не создаёт дубль. */
  id: string
  idВещи: string
  /** Название вещи на момент постановки — для панели прогресса. */
  название: string
  /** Способ становится известен в момент обработки (пакшот проверяется по Оригиналу). */
  способ: СпособОцифровки | null
  статус: СтатусЗадачи
  /** Сколько попыток уже израсходовано (накопительно, в том числе между запусками). */
  попытки: number
  последняяОшибка?: string
  датаСоздания: string
  датаОбновления: string
}

/** Состояние очереди оцифровки целиком. */
export interface СостояниеОчереди {
  id: 'active'
  статус: СтатусОчереди
  задачи: ЗадачаОчереди[]
  /** `id` вещи, которая обрабатывается прямо сейчас. */
  текущая?: string
  /** Последняя ошибка — показывается в панели прогресса. */
  последняяОшибка?: string
  датаНачала: string
  датаОбновления: string
}

/** Ключ единственной записи очереди. */
export const QUEUE_ID = 'active'

/** Читает сохранённую очередь, если она есть. */
export async function loadQueue(): Promise<СостояниеОчереди | undefined> {
  const db = await getDb()
  return db.get('queue', QUEUE_ID)
}

/** Перезаписывает состояние очереди целиком. */
export async function saveQueue(state: СостояниеОчереди): Promise<void> {
  const db = await getDb()
  await db.put('queue', state)
}

/** Убирает очередь из хранилища (например, когда всё оцифровано). */
export async function clearQueue(): Promise<void> {
  const db = await getDb()
  await db.delete('queue', QUEUE_ID)
}
