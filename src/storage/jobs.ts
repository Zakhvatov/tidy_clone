/**
 * Стор `jobs`: жизненный цикл асинхронной генерации AI-версии (ADR-0006).
 *
 * Зачем отдельный стор, а не флаг в очереди: генерация запускается и из
 * карточки вещи, и массово, а после `202` ей нужны два значения, которых нет
 * ни у очереди, ни у вещи, — `Idempotency-Key` и `taskId` провайдера. С их
 * помощью закрытие вкладки не теряет ни оплаченную задачу, ни деньги:
 * при следующем открытии клиент допрашивает ту же задачу, а повторный `POST`
 * с тем же ключом не списывает второй раз.
 *
 * Запись одна на вещь (`id` = `id` вещи): вторая генерация для той же вещи
 * невозможна, пока не завершена или не удалена текущая. Запись живёт до
 * успешного сохранения картинки (затем удаляется) или до явного отказа.
 *
 * Очередь — служебная сущность, поэтому тип лежит здесь, рядом со стором,
 * и не попадает в `domain/types.ts`.
 */

import { getDb } from './db'

/**
 * Статус задачи генерации.
 *
 * - `создаётся` — `POST /generate` ещё не ответил, `taskId` нет;
 * - `ждёт` — задача поставлена, идёт опрос статуса;
 * - `просрочена` — сеанс ожидания (5 минут) истёк: `taskId` сохранён,
 *   «Повторить» допрашивает ту же задачу, а не платит заново;
 * - `не удалось` — терминальный отказ: новая попытка создаст новую задачу
 *   (и оплату), поэтому у неё будет новый `Idempotency-Key`.
 */
export type СтатусЗадачиГенерации = 'создаётся' | 'ждёт' | 'просрочена' | 'не удалось'

/** Задача генерации AI-версии одной вещи. */
export interface ЗадачаГенерации {
  /** `id` задачи = `id` вещи: одна активная генерация на вещь. */
  id: string
  idВещи: string
  /**
   * `Idempotency-Key` (≤64 символов), который уйдёт провайдеру. Генерируется
   * до первого `POST` и хранится: потерянный ответ не стоит второй оплаты.
   * Меняется только при новой попытке после терминального отказа провайдера.
   */
  ключ: string
  /**
   * Номер попытки постановки задачи. Первый POST по вещи всегда идёт с ключом
   * попытки 1 — детерминированность ключа и есть защита от двойной оплаты.
   */
  попытка: number
  /**
   * Id задачи у провайдера. Появился — генерация оплачена, и любая
   * перезагрузка приложения продолжается с допроса этой же задачи.
   */
  taskId?: string
  /** Slug модели, с которой поставлена задача (для лога и повтора). */
  модель?: string
  /** Перегенерация: результат заменит уже существующую AI-версию. */
  force: boolean
  статус: СтатусЗадачиГенерации
  /** Последняя понятная ошибка — показывается на экране статуса. */
  последняяОшибка?: string
  /**
   * Начало текущего сеанса ожидания (ISO-8601). Потолок в 5 минут — потолок
   * живого сеанса, а не отказ: по его истечении статус становится
   * «просрочена», а `taskId` сохраняется.
   */
  датаСеанса?: string
  датаСоздания: string
  датаОбновления: string
}

/** Читает задачу генерации вещи, если она есть. */
export async function loadJob(idВещи: string): Promise<ЗадачаГенерации | undefined> {
  const db = await getDb()
  return db.get('jobs', idВещи)
}

/** Перезаписывает задачу генерации целиком. */
export async function saveJob(job: ЗадачаГенерации): Promise<void> {
  const db = await getDb()
  await db.put('jobs', job)
}

/**
 * Удаляет задачу генерации. Вызывается после успешного сохранения картинки
 * (задача выполнена) и при явном сбросе — гонять её дольше незачем.
 */
export async function removeJob(idВещи: string): Promise<void> {
  const db = await getDb()
  await db.delete('jobs', idВещи)
}

/** Все задачи генерации — нужно кнопке «Забрать готовое». */
export async function loadJobs(): Promise<ЗадачаГенерации[]> {
  const db = await getDb()
  const jobs = await db.getAll('jobs')
  return jobs.sort((a, b) => a.датаСоздания.localeCompare(b.датаСоздания))
}
